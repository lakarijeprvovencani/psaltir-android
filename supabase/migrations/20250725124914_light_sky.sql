/*
  # Create kathismas table

  1. New Tables
    - `kathismas`
      - `id` (integer, primary key) - Kathisma number (1-20)
      - `title` (text) - Title of the kathisma
      - `psalms_range` (text) - Range of psalms (e.g., "1-8")
      - `description` (text) - Description of the kathisma
      - `psalm_numbers` (integer array) - Array of psalm numbers in this kathisma
      - `created_at` (timestamp)

  2. Security
    - Enable RLS on `kathismas` table
    - Add policy for public read access (since this is religious content)
*/

CREATE TABLE IF NOT EXISTS kathismas (
  id integer PRIMARY KEY,
  title text NOT NULL,
  psalms_range text NOT NULL,
  description text NOT NULL DEFAULT '',
  psalm_numbers integer[] NOT NULL DEFAULT '{}',
  created_at timestamptz DEFAULT now()
);

ALTER TABLE kathismas ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Anyone can read kathismas"
  ON kathismas
  FOR SELECT
  TO public
  USING (true);

