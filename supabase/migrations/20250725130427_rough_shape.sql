/*
  # Create psalms table and connect with kathismas

  1. New Tables
    - `psalms`
      - `id` (integer, primary key) - Број псалма (1-150)
      - `title` (text) - Наслов псалма
      - `subtitle` (text) - Поднаслов или кратак опис
      - `content` (text[]) - Садржај псалма као низ стихова
      - `kathisma_id` (integer) - Веза са катизмом
      - `note` (text, nullable) - Додатне напомене
      - `created_at` (timestamp) - Време креирања

  2. Security
    - Enable RLS on `psalms` table
    - Add policy for public read access to psalms

  3. Sample Data
    - Insert sample psalms for first kathisma (Psalms 1-8)
    - Each psalm includes Serbian Orthodox text content
*/

-- Create psalms table
CREATE TABLE IF NOT EXISTS psalms (
  id integer PRIMARY KEY,
  title text NOT NULL,
  subtitle text NOT NULL,
  content text[] NOT NULL DEFAULT '{}',
  kathisma_id integer NOT NULL,
  note text,
  created_at timestamptz DEFAULT now()
);

-- Add foreign key constraint
ALTER TABLE psalms 
ADD CONSTRAINT psalms_kathisma_id_fkey 
FOREIGN KEY (kathisma_id) REFERENCES kathismas(id) ON DELETE CASCADE;

-- Enable RLS
ALTER TABLE psalms ENABLE ROW LEVEL SECURITY;

-- Create policy for public read access
CREATE POLICY "Anyone can read psalms"
  ON psalms
  FOR SELECT
  TO public
  USING (true);

